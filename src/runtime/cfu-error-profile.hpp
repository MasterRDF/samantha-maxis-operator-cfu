struct Relocation { size_t offset, next; uintptr_t target; bool counter; };
inline constexpr Relocation Relocations[]{
    {16,20,1364112,false}, {68,72,0,true},
    {97,101,754080,false}, {139,143,755099,false}
};
inline uintptr_t relative(uintptr_t next, int32_t displacement) {
    if (displacement < 0) {
        const auto distance=static_cast<uintptr_t>(-static_cast<int64_t>(displacement));
        return next>=distance?next-distance:0;
    }
    const auto distance=static_cast<uintptr_t>(displacement);
    return next<=std::numeric_limits<uintptr_t>::max()-distance?next+distance:0;
}
template<class Reader> bool matches(Reader&& reader, uintptr_t base) {
    namespace p=client_error_profile;
    std::array<unsigned char,p::Hook.size()> hook{};
    std::array<unsigned char,p::Tail.size()> tail{};
    std::array<unsigned char,p::Initializer.size()> initializer{};
    if(!reader(base+p::HookRva,hook.data(),hook.size())||hook!=p::Hook||
       !reader(base+p::TailRva,tail.data(),tail.size())||tail[0]!=0xe9||tail[5]!=0x90||
       !std::equal(tail.begin()+6,tail.end(),p::Tail.begin()+6)||
       !reader(base+p::InitializerRva,initializer.data(),initializer.size())||initializer!=p::Initializer)return false;
    int32_t jump=0;std::memcpy(&jump,tail.data()+1,sizeof jump);
    const auto code=relative(base+p::TailRva+5,jump);
    // CFU places a dedicated executable guard page after 24 KiB of table data.
    if(!code||(code&4095)||code<24576||code>std::numeric_limits<uintptr_t>::max()-Guard.size())return false;
    auto actual=Guard;
    if(!reader(code,actual.data(),actual.size()))return false;
    for(const auto& relocation:Relocations){
        int32_t displacement=0;std::memcpy(&displacement,actual.data()+relocation.offset,sizeof displacement);
        const auto target=relative(code+relocation.next,displacement);
        const auto expected=relocation.counter?code-1792:base+relocation.target;
        if(!target||target!=expected)return false;
        std::copy_n(Guard.data()+relocation.offset,4,actual.data()+relocation.offset);
    }
    return actual==Guard;
}
